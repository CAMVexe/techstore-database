/* ===== COMPRA_PROVEEDOR (cabecera + detalle) ===== */

CREATE OR ALTER PROCEDURE NEW_COMPRA_PROVEEDOR @p_ID_PROVEEDOR INT, @p_ID_COMPRA INT OUTPUT AS
BEGIN
