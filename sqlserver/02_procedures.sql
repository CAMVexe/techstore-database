    SET @p_ID_COMPRA = SCOPE_IDENTITY();
END
GO

-- Inserta la línea y acumula el total de la orden en una sola transacción
CREATE OR ALTER PROCEDURE NEW_DETALLE_COMPRA
    @p_ID_COMPRA INT, @p_ID_PRODUCTO INT, @p_CANTIDAD INT, @p_PRECIO_COMPRA DECIMAL(10,2)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO DETALLE_COMPRA (CANTIDAD, PRECIO_COMPRA, SUBTOTAL, ID_COMPRA, ID_PRODUCTO)
        VALUES (@p_CANTIDAD, @p_PRECIO_COMPRA, @p_CANTIDAD * @p_PRECIO_COMPRA, @p_ID_COMPRA, @p_ID_PRODUCTO);

        UPDATE COMPRA_PROVEEDOR
        SET TOTAL = TOTAL + (@p_CANTIDAD * @p_PRECIO_COMPRA)
        WHERE ID_COMPRA = @p_ID_COMPRA;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO

-- Pasar a 'Recibida' dispara TRIG_STOCK_COMPRA (aumenta stock)
CREATE OR ALTER PROCEDURE UPD_ESTADO_COMPRA @p_ID_COMPRA INT, @p_ESTADO VARCHAR(15) AS
BEGIN
    UPDATE COMPRA_PROVEEDOR SET ESTADO = @p_ESTADO WHERE ID_COMPRA = @p_ID_COMPRA;
END
GO

/* ===== GARANTIA ===== */

-- Falla si el detalle de venta no existe o no pertenece al usuario solicitante
CREATE OR ALTER PROCEDURE NEW_GARANTIA
    @p_ID_DETALLE_VENTA INT, @p_ID_USUARIO INT, @p_MOTIVO VARCHAR(150), @p_DESCRIPCION VARCHAR(300)
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT EXISTS (
        SELECT 1
        FROM DETALLE_VENTA dv
        JOIN VENTA v ON v.ID_VENTA = dv.ID_VENTA
        WHERE dv.ID_DETALLE_VENTA = @p_ID_DETALLE_VENTA AND v.ID_USUARIO = @p_ID_USUARIO
    )
        THROW 50002, 'Esta compra no pertenece al usuario solicitante', 1;

    INSERT INTO GARANTIA (MOTIVO, DESCRIPCION, ID_DETALLE_VENTA)
    VALUES (@p_MOTIVO, @p_DESCRIPCION, @p_ID_DETALLE_VENTA);
END
GO

-- FECHA_RESOLUCION solo se llena al aprobar/rechazar (si vuelve a 'En proceso' queda NULL)
CREATE OR ALTER PROCEDURE UPD_ESTADO_GARANTIA
    @p_ID_GARANTIA INT,
    @p_ESTADO VARCHAR(15)
AS
BEGIN
    UPDATE GARANTIA
    SET ESTADO = @p_ESTADO,
        FECHA_RESOLUCION = CASE WHEN @p_ESTADO IN ('Aprobada', 'Rechazada') THEN GETDATE() ELSE NULL END
    WHERE ID_GARANTIA = @p_ID_GARANTIA;
END
