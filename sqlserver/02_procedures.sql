-- Con @p_ESTADO el admin puede activar/desactivar un producto
CREATE OR ALTER PROCEDURE UPD_PRODUCTO
    @p_ID_PRODUCTO INT, @p_NOMBRE VARCHAR(80), @p_DESCRIPCION VARCHAR(300), @p_PRECIO DECIMAL(10,2),
    @p_STOCK_MIN INT, @p_ESTADO VARCHAR(15), @p_ID_CATEGORIA INT, @p_ID_MARCA INT
AS
BEGIN
    UPDATE PRODUCTO SET NOMBRE = @p_NOMBRE, DESCRIPCION = @p_DESCRIPCION, PRECIO = @p_PRECIO,
        STOCK_MIN = @p_STOCK_MIN, ESTADO = @p_ESTADO, ID_CATEGORIA = @p_ID_CATEGORIA, ID_MARCA = @p_ID_MARCA
    WHERE ID_PRODUCTO = @p_ID_PRODUCTO;
END
GO

-- Borrado lógico si el producto tiene historial; físico (limpiando carritos) si no.
CREATE OR ALTER PROCEDURE DEL_PRODUCTO @p_ID_PRODUCTO INT AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF EXISTS (SELECT 1 FROM DETALLE_VENTA WHERE ID_PRODUCTO = @p_ID_PRODUCTO)
       OR EXISTS (SELECT 1 FROM DETALLE_COMPRA WHERE ID_PRODUCTO = @p_ID_PRODUCTO)
       OR EXISTS (SELECT 1 FROM HISTORIAL_INVENTARIO WHERE ID_PRODUCTO = @p_ID_PRODUCTO)
        UPDATE PRODUCTO SET ESTADO = 'Inactivo' WHERE ID_PRODUCTO = @p_ID_PRODUCTO;
    ELSE
    BEGIN
        BEGIN TRANSACTION;
        DELETE FROM DETALLE_CARRITO WHERE ID_PRODUCTO = @p_ID_PRODUCTO;
        DELETE FROM PRODUCTO WHERE ID_PRODUCTO = @p_ID_PRODUCTO;
        COMMIT TRANSACTION;
    END
END
GO

/* ===== VENTA (cabecera + detalle) ===== */

-- El ID generado se devuelve por parámetro OUTPUT para usarlo en el detalle
CREATE OR ALTER PROCEDURE NEW_VENTA
    @p_ID_USUARIO INT,
    @p_IMPUESTO DECIMAL(10,2),
    @p_DESCUENTO DECIMAL(10,2),
    @p_ID_VENTA INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO VENTA (IMPUESTO, DESCUENTO, ID_USUARIO)
        VALUES (@p_IMPUESTO, @p_DESCUENTO, @p_ID_USUARIO);

        SET @p_ID_VENTA = CONVERT(INT, SCOPE_IDENTITY());

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO

-- CAMBIO vs. versión anterior: ya NO recibe @p_PRECIO_UNITARIO. El precio se lee de
-- PRODUCTO dentro del procedimiento (el diccionario lo define como copia del precio
-- vigente al momento de la venta) y solo se vende producto 'Activo'.
-- El INSERT dispara TRIG_STOCK_VENTA (valida y descuenta stock).
CREATE OR ALTER PROCEDURE NEW_DETALLE_VENTA
    @p_ID_VENTA INT,
    @p_ID_PRODUCTO INT,
    @p_CANTIDAD INT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @v_PRECIO DECIMAL(10,2);

    BEGIN TRY
        BEGIN TRANSACTION;

        SELECT @v_PRECIO = PRECIO
        FROM PRODUCTO
        WHERE ID_PRODUCTO = @p_ID_PRODUCTO AND ESTADO = 'Activo';

        IF @v_PRECIO IS NULL
            THROW 50003, 'Producto inexistente o inactivo', 1;

        INSERT INTO DETALLE_VENTA (CANTIDAD, PRECIO_UNITARIO, SUBTOTAL, ID_VENTA, ID_PRODUCTO)
        VALUES (@p_CANTIDAD, @v_PRECIO, @p_CANTIDAD * @v_PRECIO, @p_ID_VENTA, @p_ID_PRODUCTO);

        UPDATE VENTA
        SET TOTAL = ISNULL((SELECT SUM(SUBTOTAL) FROM DETALLE_VENTA WHERE ID_VENTA = @p_ID_VENTA), 0)
                    + ISNULL(IMPUESTO, 0) - ISNULL(DESCUENTO, 0)
        WHERE ID_VENTA = @p_ID_VENTA;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO

-- Pasar a 'Cancelada' dispara TRIG_REPOSICION_VENTA_CANCELADA (repone stock)
