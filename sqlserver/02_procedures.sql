-- Borrado lógico si el usuario tiene ventas (se preserva el historial);
-- borrado físico (con sus carritos) si nunca compró.
CREATE OR ALTER PROCEDURE DEL_USUARIO @p_ID_USUARIO INT AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF EXISTS (SELECT 1 FROM VENTA WHERE ID_USUARIO = @p_ID_USUARIO)
        UPDATE USUARIO SET ESTADO = 'Inactivo' WHERE ID_USUARIO = @p_ID_USUARIO;
    ELSE
    BEGIN
        BEGIN TRANSACTION;
        DELETE FROM DETALLE_CARRITO WHERE ID_CARRITO IN (SELECT ID_CARRITO FROM CARRITO WHERE ID_USUARIO = @p_ID_USUARIO);
        DELETE FROM CARRITO WHERE ID_USUARIO = @p_ID_USUARIO;
        DELETE FROM USUARIO WHERE ID_USUARIO = @p_ID_USUARIO;
        COMMIT TRANSACTION;
    END
END
GO

