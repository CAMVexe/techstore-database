-- Nota: a diferencia de Oracle, una vista en SQL Server no admite ORDER BY
-- (salvo con TOP); el orden se pide al consultar: SELECT * FROM VIS_... ORDER BY ...
USE TechStore;
GO

CREATE OR ALTER VIEW VIS_STOCK_BAJO AS
    SELECT p.ID_PRODUCTO, p.NOMBRE, p.STOCK, p.STOCK_MIN, c.NOMBRE AS CATEGORIA, m.NOMBRE AS MARCA
    FROM PRODUCTO p
    JOIN CATEGORIA c ON c.ID_CATEGORIA = p.ID_CATEGORIA
    JOIN MARCA m ON m.ID_MARCA = p.ID_MARCA
    WHERE p.STOCK <= p.STOCK_MIN AND p.ESTADO = 'Activo';
GO

CREATE OR ALTER VIEW VIS_VENTAS_DETALLE AS
    SELECT v.ID_VENTA, u.NOMBRE + ' ' + u.APELLIDOS AS CLIENTE, v.FECHA, p.NOMBRE AS PRODUCTO,
        dv.CANTIDAD, dv.PRECIO_UNITARIO, dv.SUBTOTAL, v.IMPUESTO, v.DESCUENTO, v.TOTAL, v.ESTADO
    FROM VENTA v
    JOIN USUARIO u ON u.ID_USUARIO = v.ID_USUARIO
    JOIN DETALLE_VENTA dv ON dv.ID_VENTA = v.ID_VENTA
    JOIN PRODUCTO p ON p.ID_PRODUCTO = dv.ID_PRODUCTO;
GO

CREATE OR ALTER VIEW VIS_HISTORIAL_INVENTARIO AS
    SELECT h.ID_MOVIMIENTO, p.NOMBRE AS PRODUCTO, h.TIPO_MOVIMIENTO, h.CANTIDAD, h.FECHA, h.OBSERVACION
    FROM HISTORIAL_INVENTARIO h
    JOIN PRODUCTO p ON p.ID_PRODUCTO = h.ID_PRODUCTO;
GO
