-- TechStore | SQL Server | 05: Índices
-- SQL Server (igual que Oracle) NO indexa automáticamente las llaves foráneas.
USE TechStore;
GO

-- Búsqueda de productos por nombre (barra de búsqueda de la tienda)
CREATE INDEX IDX_PRODUCTO_NOMBRE ON PRODUCTO(NOMBRE);

-- FK hacia la cabecera en tablas de detalle (las usan casi todas las consultas y triggers)
CREATE INDEX IDX_DETVENTA_ID_VENTA ON DETALLE_VENTA(ID_VENTA);
CREATE INDEX IDX_DETCOMPRA_ID_COMPRA ON DETALLE_COMPRA(ID_COMPRA);
CREATE INDEX IDX_DETCARRITO_ID_CARRITO ON DETALLE_CARRITO(ID_CARRITO);

-- FK que consultan DEL_USUARIO, DEL_PRODUCTO, FN_TOTAL_GASTADO_USUARIO y NEW_GARANTIA
CREATE INDEX IDX_VENTA_ID_USUARIO ON VENTA(ID_USUARIO);
CREATE INDEX IDX_CARRITO_ID_USUARIO ON CARRITO(ID_USUARIO);
CREATE INDEX IDX_DETVENTA_ID_PRODUCTO ON DETALLE_VENTA(ID_PRODUCTO);
CREATE INDEX IDX_DETCOMPRA_ID_PRODUCTO ON DETALLE_COMPRA(ID_PRODUCTO);
CREATE INDEX IDX_DETCARRITO_ID_PRODUCTO ON DETALLE_CARRITO(ID_PRODUCTO);
CREATE INDEX IDX_HIST_ID_PRODUCTO ON HISTORIAL_INVENTARIO(ID_PRODUCTO);
CREATE INDEX IDX_GARANTIA_ID_DETVENTA ON GARANTIA(ID_DETALLE_VENTA);

-- Regla del diccionario de datos: un usuario mantiene un solo carrito 'Activo' a la vez.
-- (índice único filtrado: solo aplica a las filas con ESTADO = 'Activo')
CREATE UNIQUE INDEX UX_CARRITO_USUARIO_ACTIVO ON CARRITO(ID_USUARIO) WHERE ESTADO = 'Activo';
GO
